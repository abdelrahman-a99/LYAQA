"""Generate NLP-only predictions from the bundled evaluation dataset.

Each example is parsed independently. Save extracted intents, entity pairs,
the first food name, and the first quantity with evaluation_scope="nlp".
Calorie and meal-recommendation results are not generated by this runner.
Write artifacts/evaluation/predictions_real.json under the repository root.

Run from the nutrition-ai repository root:
    python -m evaluation.run_real_predictions
"""

import json
from pathlib import Path

from app.ai.nlp.parser import parse_user_input
from app.paths import EVALUATION_DATA_DIR, EVALUATION_OUTPUT_DIR

DATASET = EVALUATION_DATA_DIR / "dataset.json"
OUT = EVALUATION_OUTPUT_DIR / "predictions_real.json"


def _ent(text, label):
    return (str(text).strip().lower(), label)


def _entities_from_parsed(parsed: dict) -> list:
    entities = []

    for food in parsed.get("foods") or []:
        name = food.get("food_name_original") or food.get("food_name_en") or ""
        if name:
            entities.append(_ent(name, "FOOD"))
        q = food.get("quantity")
        if q is not None:
            qs = str(int(q)) if float(q).is_integer() else str(q)
            entities.append(_ent(qs, "QUANTITY"))
        if food.get("unit"):
            entities.append(_ent(food["unit"], "UNIT"))

    profile = parsed.get("profile_data") or {}
    if profile.get("gender"):
        entities.append(_ent(profile["gender"], "GENDER"))
    if profile.get("weight") is not None:
        entities.append(_ent(str(int(profile["weight"])), "WEIGHT"))
    if profile.get("height") is not None:
        entities.append(_ent(str(int(profile["height"])), "HEIGHT"))
    if profile.get("activity_level"):
        entities.append(_ent(profile["activity_level"], "ACTIVITY"))
    if profile.get("goal"):
        entities.append(_ent(profile["goal"], "GOAL"))
    for r in profile.get("dietary_restrictions") or []:
        entities.append(_ent(r, "DIET"))
    for r in profile.get("allergies") or []:
        entities.append(_ent(r, "RESTRICTION"))
    for r in profile.get("forbidden_foods") or []:
        entities.append(_ent(r, "RESTRICTION"))

    if parsed.get("meal_type"):
        entities.append(_ent(parsed["meal_type"], "MEAL_TYPE"))

    return entities


def _first_food(parsed):
    foods = parsed.get("foods") or []
    if not foods:
        return ""
    return foods[0].get("food_name_original") or foods[0].get("food_name_en") or ""


def _first_qty(parsed):
    foods = parsed.get("foods") or []
    if not foods:
        return [0.0, ""]
    return [float(foods[0].get("quantity") or 0.0), str(foods[0].get("unit") or "")]


def main():
    from app.config import load_environment

    load_environment(".env")

    with open(DATASET, encoding="utf-8") as f:
        examples = json.load(f)["examples"]

    predictions = []
    for i, ex in enumerate(examples, 1):
        print(f"[{i}/{len(examples)}] {ex['input'][:70]}")
        try:
            parsed = parse_user_input(ex["input"])
        except Exception as exc:
            print(f"   ERROR: {exc}")
            parsed = {"intent": "unknown", "foods": [], "profile_data": None}

        predictions.append(
            {
                "intent": parsed.get("intent", ""),
                "entities": _entities_from_parsed(parsed),
                "food_name": _first_food(parsed),
                "quantity": _first_qty(parsed),
            }
        )

    Path(OUT).parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(
            {
                "description": "Real Task 1 predictions against dataset.json.",
                "evaluation_scope": "nlp",
                "predictions": predictions,
            },
            f,
            ensure_ascii=False,
            indent=2,
        )

    print(f"\nSaved {len(predictions)} predictions → {OUT}")


if __name__ == "__main__":
    main()
